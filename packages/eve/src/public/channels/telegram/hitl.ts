/**
 * Telegram HITL inline keyboard rendering and compact callback decode helpers.
 *
 * Telegram limits `InlineKeyboardButton.callback_data` to 64 bytes, so
 * eve stores compact callback ids in durable channel state and remaps
 * them back to full input responses inside the channel deliver hook.
 */

import type { MessageContent } from "#shared/message-content.js";

import { resolvedPromptLabel } from "#channel/resolved-prompt.js";
import type { RequestSettlement } from "#channel/interaction-prompts.js";
import { type Answer, parseAnswer, parseAnswers, type ValidatedAnswer } from "#shared/input.js";
import type { InteractionOption } from "#protocol/session-events/families/interaction.js";
import type { Interaction } from "#channel/interaction-prompts.js";
import { chunk, truncate } from "#public/channels/text.js";

/** Prefix used in Telegram callback_data values generated by eve. */
export const TELEGRAM_HITL_CALLBACK_PREFIX = "eve:";

/** Synthetic request id prefix sent through `send()` for callback queries. */
export const TELEGRAM_CALLBACK_RESPONSE_PREFIX = "telegram_callback:";

/** Synthetic request id prefix the deliver hook uses for replies to ForceReply prompts. */
export const TELEGRAM_REPLY_RESPONSE_PREFIX = "telegram_reply:";

const TELEGRAM_BUTTON_LABEL_MAX_LENGTH = 64;
const TELEGRAM_INPUT_PLACEHOLDER_MAX_LENGTH = 64;
const TELEGRAM_PROMPT_MAX_LENGTH = 4000;
const TELEGRAM_INLINE_ROW_SIZE = 2;
/** Keeps an edited prompt under Telegram's 4096-character message cap. */
const TELEGRAM_RESOLVED_LABEL_MAX_LENGTH = 90;

/**
 * Durable HITL state. `hitlCallbacks` maps compact callback ids to their stored
 * `Answer`. `nextHitlCallbackId` is the monotonic id counter.
 * `pendingFreeformReplies` maps a posted prompt's message id to the awaiting
 * requestId.
 */
export interface TelegramHitlState {
  hitlCallbacks?: Record<string, Answer>;
  nextHitlCallbackId?: number;
  pendingFreeformReplies?: Record<string, string>;
  /** Posted prompts with inline keyboards, keyed by requestId, until eve resolves them. */
  hitlPrompts?: Record<string, TelegramHitlPrompt>;
}

/** What a posted prompt needs so its message can be edited once eve resolves it. */
export interface TelegramHitlPrompt {
  readonly messageId: string;
  readonly options: readonly Pick<InteractionOption, "id" | "label">[];
  readonly text: string;
}

/**
 * Rendered Telegram message body for one pending input request.
 * `freeformRequestId` is set only for ForceReply prompts (option-less requests).
 * After posting such a prompt, call {@link registerTelegramFreeformPrompt}.
 * Option requests instead carry an inline-keyboard `replyMarkup`.
 */
export interface TelegramInteractionMessage {
  readonly freeformRequestId?: string;
  readonly replyMarkup?: Readonly<Record<string, unknown>>;
  readonly text: string;
}

/** Renders one `Interaction` as Telegram inline keyboard or ForceReply markup. */
export function renderTelegramInteraction(
  request: Interaction,
  state: TelegramHitlState,
): TelegramInteractionMessage {
  const options = request.request.options;
  if (options && options.length > 0) {
    const buttons = options.map((option) => ({
      callback_data: registerTelegramCallback(state, {
        optionId: option.id,
        interactionId: request.interactionId,
      }),
      text: truncate(option.label, TELEGRAM_BUTTON_LABEL_MAX_LENGTH),
    }));
    return {
      replyMarkup: {
        inline_keyboard: chunk(buttons, TELEGRAM_INLINE_ROW_SIZE),
      },
      text: truncate(request.request.prompt, TELEGRAM_PROMPT_MAX_LENGTH),
    };
  }

  return {
    freeformRequestId: request.interactionId,
    replyMarkup: {
      force_reply: true,
      input_field_placeholder: truncate("Type your answer", TELEGRAM_INPUT_PLACEHOLDER_MAX_LENGTH),
      selective: true,
    },
    text: truncate(request.request.prompt, TELEGRAM_PROMPT_MAX_LENGTH),
  };
}

/** Records the Telegram message id that a freeform answer should reply to. */
export function registerTelegramFreeformPrompt(
  state: TelegramHitlState,
  input: { readonly messageId: string; readonly requestId: string },
): void {
  state.pendingFreeformReplies = {
    ...state.pendingFreeformReplies,
    [input.messageId]: input.requestId,
  };
}

/** Records a posted inline-keyboard prompt so {@link takeTelegramResolvedPrompt} can edit it. */
export function registerTelegramHitlPrompt(
  state: TelegramHitlState,
  request: Interaction,
  posted: { readonly messageId: string; readonly text: string },
): void {
  state.hitlPrompts = {
    ...state.hitlPrompts,
    [request.interactionId]: {
      ...posted,
      options: (request.request.options ?? []).map(({ id, label }) => ({ id, label })),
    },
  };
}

/**
 * Forgets a resolved prompt, returning the edit that
 * replaces its keyboard with the outcome, or `undefined` when eve never posted it.
 */
export function takeTelegramResolvedPrompt(
  state: TelegramHitlState,
  resolution: RequestSettlement,
): { readonly messageId: string; readonly text: string } | undefined {
  const prompt = state.hitlPrompts?.[resolution.interactionId];
  if (prompt === undefined) return undefined;
  const { [resolution.interactionId]: _, ...rest } = state.hitlPrompts ?? {};
  state.hitlPrompts = rest;
  return {
    messageId: prompt.messageId,
    text: telegramResolvedPromptText(prompt.text, resolvedPromptLabel(resolution, prompt.options)),
  };
}

/** A resolved prompt's text: the prompt it asked, then `label`, how it ended. */
export function telegramResolvedPromptText(promptText: string, label: string): string {
  return `${promptText}\n\n${truncate(label, TELEGRAM_RESOLVED_LABEL_MAX_LENGTH)}`;
}

/**
 * Wraps Telegram callback data as a synthetic `Answer` (requestId prefixed
 * with `telegram_callback:`, optionId hardcoded to `"selected"`). It is a
 * placeholder; {@link resolveTelegramAnswers} resolves it back to the real
 * stored response.
 */
export function telegramCallbackAnswer(callbackData: string): ValidatedAnswer {
  return parseAnswer({
    interactionId: `${TELEGRAM_CALLBACK_RESPONSE_PREFIX}${callbackData}`,
    optionId: "selected",
  });
}

/** Wraps a reply-to-message id in an `Answer` shape for delivery. */
export function telegramReplyAnswer(input: {
  readonly messageId: string;
  readonly text: string;
}): ValidatedAnswer {
  return parseAnswer({
    interactionId: `${TELEGRAM_REPLY_RESPONSE_PREFIX}${input.messageId}`,
    text: input.text,
  });
}

/**
 * Wraps a text message that replied to a bot message as a synthetic response,
 * so the deliver hook can match it to a pending ForceReply prompt.
 */
export function telegramReplyAnswers(
  replyToBotMessageId: unknown,
  message: MessageContent | undefined,
): ValidatedAnswer[] {
  if (typeof replyToBotMessageId !== "string") return [];
  const text =
    typeof message === "string"
      ? message
      : (message ?? []).flatMap((part) => (part.type === "text" ? [part.text] : [])).join("\n");
  if (text.trim().length === 0) return [];
  return [telegramReplyAnswer({ messageId: replyToBotMessageId, text })];
}

/** True when an input response needs Telegram-specific durable-state remapping. */
export function isTelegramSyntheticResponse(response: Answer): boolean {
  return (
    response.interactionId.startsWith(TELEGRAM_CALLBACK_RESPONSE_PREFIX) ||
    response.interactionId.startsWith(TELEGRAM_REPLY_RESPONSE_PREFIX)
  );
}

/** Remaps compact Telegram callback/reply ids into real eve input responses. */
export function resolveTelegramAnswers(
  state: TelegramHitlState,
  responses: readonly Answer[],
): ValidatedAnswer[] {
  const resolved: Answer[] = [];

  for (const response of responses) {
    if (response.interactionId.startsWith(TELEGRAM_CALLBACK_RESPONSE_PREFIX)) {
      const callbackData = response.interactionId.slice(TELEGRAM_CALLBACK_RESPONSE_PREFIX.length);
      // The mapping outlives the press: a later press of the same button still
      // reaches the session, which reads an answered request's option as new input.
      const mapped = state.hitlCallbacks?.[callbackData];
      if (mapped !== undefined) resolved.push(mapped);
      continue;
    }

    if (response.interactionId.startsWith(TELEGRAM_REPLY_RESPONSE_PREFIX)) {
      const messageId = response.interactionId.slice(TELEGRAM_REPLY_RESPONSE_PREFIX.length);
      const requestId = state.pendingFreeformReplies?.[messageId];
      if (requestId !== undefined && response.text !== undefined) {
        resolved.push({ interactionId: requestId, text: response.text });
        delete state.pendingFreeformReplies?.[messageId];
      }
      continue;
    }

    resolved.push(response);
  }

  return [...parseAnswers(resolved)];
}

function registerTelegramCallback(state: TelegramHitlState, response: Answer): string {
  const next = state.nextHitlCallbackId ?? 0;
  state.nextHitlCallbackId = next + 1;
  const callbackData = `${TELEGRAM_HITL_CALLBACK_PREFIX}${next.toString(36)}`;
  state.hitlCallbacks = {
    ...state.hitlCallbacks,
    [callbackData]: response,
  };
  return callbackData;
}
