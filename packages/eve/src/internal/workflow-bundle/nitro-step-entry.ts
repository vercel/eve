import { realpathSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";

import type { CompiledExtensionMount } from "#compiler/manifest.js";
import { normalizeEsmImportSpecifier } from "#internal/application/import-specifier.js";
import {
  parseExtensionMountId,
  resolveExtensionMountForId,
  tagExtensionMountId,
} from "#internal/bundler/extension-mount-plugin.js";
import {
  applyWorkflowTransform,
  type WorkflowManifest,
} from "#internal/workflow-bundle/workflow-builders.js";

export interface NitroStepEntrypointDiscoveredEntries {
  readonly discoveredSerdeFiles: readonly string[];
  readonly discoveredSteps: readonly string[];
}

export async function writeNitroStepEntrypoint(input: {
  readonly builtinsPath: string;
  readonly discoveredEntries: NitroStepEntrypointDiscoveredEntries;
  readonly extensionMounts?: readonly CompiledExtensionMount[];
  readonly extensionOverridePaths?: ReadonlyMap<string, string>;
  readonly outfile: string;
  readonly projectRoot: string;
  readonly sideEffectFiles: readonly string[];
  readonly workingDir: string;
}): Promise<{ readonly manifest: WorkflowManifest; readonly stepTargets: readonly string[] }> {
  const stepFiles = [...input.discoveredEntries.discoveredSteps].sort();
  const stepFileSet = new Set(stepFiles);
  const serdeOnlyFiles = [...input.discoveredEntries.discoveredSerdeFiles]
    .sort()
    .filter((filePath) => !stepFileSet.has(filePath));
  const manifest = await collectNitroStepManifest({
    extensionMounts: input.extensionMounts,
    projectRoot: input.projectRoot,
    stepFiles,
    serdeOnlyFiles,
    workingDir: input.workingDir,
  });
  await mkdir(dirname(input.outfile), { recursive: true });
  const mountInitTargets = await writeExtensionMountInitTargets({
    extensionMounts: input.extensionMounts,
    extensionOverridePaths: input.extensionOverridePaths,
    outDir: dirname(input.outfile),
    stepFiles,
  });
  const stepTargets = [
    input.builtinsPath,
    ...input.sideEffectFiles,
    ...mountInitTargets,
    ...stepFiles,
    ...serdeOnlyFiles,
  ];
  const lines = [
    "// Generated by eve. Do not edit by hand.",
    ...stepTargets.map((path) => `import ${JSON.stringify(normalizeEsmImportSpecifier(path))};`),
    "export const __steps_registered = true;",
    "",
  ];

  await writeFile(input.outfile, lines.join("\n"));

  return { manifest, stepTargets };
}

function canonicalPath(path: string): string {
  try {
    return realpathSync(path);
  } catch {
    return resolve(path);
  }
}

async function writeExtensionMountInitTargets(input: {
  readonly extensionMounts: readonly CompiledExtensionMount[] | undefined;
  readonly extensionOverridePaths: ReadonlyMap<string, string> | undefined;
  readonly outDir: string;
  readonly stepFiles: readonly string[];
}): Promise<string[]> {
  const mounts = input.extensionMounts;
  if (mounts === undefined || mounts.length === 0) return [];
  const byId = new Map(mounts.map((mount) => [mount.mountId, mount]));
  const overrideMounts = new Map(
    [...(input.extensionOverridePaths ?? [])].map(([path, mountId]) => [
      canonicalPath(path),
      mountId,
    ]),
  );
  const activeMountIds = new Set<string>();
  for (const entryId of input.stepFiles) {
    const { filePath, mountId } = parseExtensionMountId(entryId);
    if (mountId !== undefined && byId.has(mountId)) activeMountIds.add(mountId);
    const overrideMountId = overrideMounts.get(canonicalPath(filePath));
    if (overrideMountId !== undefined && byId.has(overrideMountId)) {
      activeMountIds.add(overrideMountId);
    }
  }
  if (activeMountIds.size === 0) return [];

  for (const mount of mounts) {
    for (const activeId of activeMountIds) {
      if (activeId.startsWith(`${mount.mountId}/`)) {
        activeMountIds.add(mount.mountId);
      }
    }
  }

  const ordered = [...activeMountIds]
    .map((mountId) => byId.get(mountId)!)
    .sort(
      (left, right) =>
        left.mountId.length - right.mountId.length || left.mountId.localeCompare(right.mountId),
    );
  const targets: string[] = [];
  for (const [index, mount] of ordered.entries()) {
    if (mount.programmaticImport === undefined) {
      targets.push(tagExtensionMountId(mount.mountSourcePath, mount.mountId));
    } else {
      const initPath = join(input.outDir, `extension-mount-${index}.mjs`);
      const specifier = tagExtensionMountId(mount.programmaticImport.specifier, mount.mountId);
      await writeFile(
        initPath,
        [
          "// Generated by eve. Do not edit by hand.",
          `import __eveExtension from ${JSON.stringify(specifier)};`,
          `__eveExtension(${JSON.stringify(mount.programmaticImport.config)});`,
          "",
        ].join("\n"),
      );
      targets.push(initPath);
    }
  }
  return targets;
}

async function collectNitroStepManifest(input: {
  readonly extensionMounts: readonly CompiledExtensionMount[] | undefined;
  readonly projectRoot: string;
  readonly serdeOnlyFiles: readonly string[];
  readonly stepFiles: readonly string[];
  readonly workingDir: string;
}): Promise<WorkflowManifest> {
  const manifest: WorkflowManifest = {};
  const files = [...input.stepFiles, ...input.serdeOnlyFiles];

  for (const entryId of files) {
    const { filePath } = parseExtensionMountId(entryId);
    const extensionMount = resolveExtensionMountForId(entryId, input.extensionMounts);
    const source = await readFile(filePath, "utf8");
    const relativeFilepath = createManifestRelativeFilepath(input.workingDir, filePath);
    const transformed = await applyWorkflowTransform(
      relativeFilepath,
      source,
      "step",
      filePath,
      input.projectRoot,
      undefined,
      extensionMount,
    );

    mergeWorkflowManifest(manifest, transformed.workflowManifest);
  }

  return manifest;
}

function mergeWorkflowManifest(target: WorkflowManifest, source: WorkflowManifest): void {
  target.steps = mergeWorkflowManifestSection(target.steps, source.steps);
  target.workflows = mergeWorkflowManifestSection(target.workflows, source.workflows);
  target.classes = mergeWorkflowManifestSection(target.classes, source.classes);
}

function mergeWorkflowManifestSection<
  TSection extends Record<string, Record<string, object>> | undefined,
>(target: TSection, source: TSection): TSection {
  if (source === undefined) {
    return target;
  }

  const nextSection = {
    ...target,
  } as Record<string, Record<string, object>>;

  for (const [relativeFileName, entries] of Object.entries(source)) {
    nextSection[relativeFileName] = {
      ...nextSection[relativeFileName],
      ...entries,
    };
  }

  return nextSection as TSection;
}

function createManifestRelativeFilepath(workingDir: string, absolutePath: string): string {
  const normalizedFile = absolutePath.replaceAll("\\", "/");
  const normalizedWorkingDir = workingDir.replaceAll("\\", "/");
  let relativePath = relative(normalizedWorkingDir, normalizedFile).replaceAll("\\", "/");

  if (relativePath.startsWith("../")) {
    relativePath = relativePath
      .split("/")
      .filter((part) => part !== "..")
      .join("/");
  }

  return relativePath;
}
