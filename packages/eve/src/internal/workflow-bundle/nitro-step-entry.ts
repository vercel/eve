import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, relative } from "node:path";

import { normalizeEsmImportSpecifier } from "#internal/application/import-specifier.js";
import {
  applyWorkflowTransform,
  type WorkflowManifest,
} from "#internal/workflow-bundle/workflow-builders.js";

export interface NitroStepEntrypointDiscoveredEntries {
  readonly discoveredSerdeFiles: readonly string[];
  readonly discoveredSteps: readonly string[];
}

/**
 * Writes the hosted Nitro step entrypoint source and returns the manifest
 * metadata discovered from the imported step and serde files, plus the
 * absolute paths the entry imports.
 */
export async function writeNitroStepEntrypoint(input: {
  readonly builtinsPath: string;
  readonly discoveredEntries: NitroStepEntrypointDiscoveredEntries;
  readonly outfile: string;
  readonly projectRoot: string;
  readonly sideEffectFiles: readonly string[];
  readonly workingDir: string;
}): Promise<{ readonly manifest: WorkflowManifest; readonly stepTargets: readonly string[] }> {
  const stepFiles = [...input.discoveredEntries.discoveredSteps].sort();
  const stepFileSet = new Set(stepFiles);
  const serdeOnlyFiles = [...input.discoveredEntries.discoveredSerdeFiles]
    .sort()
    .filter((filePath) => !stepFileSet.has(filePath));
  const manifest = await collectNitroStepManifest({
    projectRoot: input.projectRoot,
    stepFiles,
    serdeOnlyFiles,
    workingDir: input.workingDir,
  });
  const stepTargets = [
    input.builtinsPath,
    ...input.sideEffectFiles,
    ...stepFiles,
    ...serdeOnlyFiles,
  ];
  const lines = [
    "// Generated by eve. Do not edit by hand.",
    ...stepTargets.map((path) => `import ${JSON.stringify(normalizeEsmImportSpecifier(path))};`),
    "export const __steps_registered = true;",
    "",
  ];

  await mkdir(dirname(input.outfile), { recursive: true });
  await writeFile(input.outfile, lines.join("\n"));

  return { manifest, stepTargets };
}

async function collectNitroStepManifest(input: {
  readonly projectRoot: string;
  readonly serdeOnlyFiles: readonly string[];
  readonly stepFiles: readonly string[];
  readonly workingDir: string;
}): Promise<WorkflowManifest> {
  const manifest: WorkflowManifest = {};
  const files = [...input.stepFiles, ...input.serdeOnlyFiles];

  for (const filePath of files) {
    const source = await readFile(filePath, "utf8");
    const relativeFilepath = createManifestRelativeFilepath(input.workingDir, filePath);
    const transformed = await applyWorkflowTransform(
      relativeFilepath,
      source,
      "step",
      filePath,
      input.projectRoot,
    );

    mergeWorkflowManifest(manifest, transformed.workflowManifest);
  }

  return manifest;
}

function mergeWorkflowManifest(target: WorkflowManifest, source: WorkflowManifest): void {
  target.steps = mergeWorkflowManifestSection(target.steps, source.steps);
  target.workflows = mergeWorkflowManifestSection(target.workflows, source.workflows);
  target.classes = mergeWorkflowManifestSection(target.classes, source.classes);
}

function mergeWorkflowManifestSection<
  TSection extends Record<string, Record<string, object>> | undefined,
>(target: TSection, source: TSection): TSection {
  if (source === undefined) {
    return target;
  }

  const nextSection = {
    ...target,
  } as Record<string, Record<string, object>>;

  for (const [relativeFileName, entries] of Object.entries(source)) {
    nextSection[relativeFileName] = {
      ...nextSection[relativeFileName],
      ...entries,
    };
  }

  return nextSection as TSection;
}

function createManifestRelativeFilepath(workingDir: string, absolutePath: string): string {
  const normalizedFile = absolutePath.replaceAll("\\", "/");
  const normalizedWorkingDir = workingDir.replaceAll("\\", "/");
  let relativePath = relative(normalizedWorkingDir, normalizedFile).replaceAll("\\", "/");

  if (relativePath.startsWith("../")) {
    relativePath = relativePath
      .split("/")
      .filter((part) => part !== "..")
      .join("/");
  }

  return relativePath;
}
