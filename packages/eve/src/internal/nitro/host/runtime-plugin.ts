import { stringifyEsmImportSpecifier } from "#internal/application/import-specifier.js";
import { resolvePackageSourceFilePath } from "#internal/application/package.js";
import type { GeneratedCompiledArtifactsFiles } from "#internal/application/compiled-artifacts.js";

/** The Nitro virtual id of eve's generated runtime plugin. */
export const EVE_RUNTIME_PLUGIN_ID = "#eve/runtime";

/** What eve's runtime plugin installs, ahead of every other runtime plugin. */
export interface HostRuntime {
  /** Captures traces locally in a dev host without authored instrumentation. */
  readonly localTracing: boolean;
  /** Installs the `run` runtime for agents with a generated-program tool. */
  readonly workflowSandbox: boolean;
}

/**
 * Generates eve's Nitro runtime plugin. Importing it installs the compiled
 * artifacts and the Workflow world, so a failure there fails the server boot
 * instead of leaving a server that rejects every request; the plugin then
 * installs what the host spec selects.
 */
export function createRuntimePluginSource(
  runtime: HostRuntime,
  compiledArtifacts: Pick<
    GeneratedCompiledArtifactsFiles,
    "bootstrapPath" | "workflowWorldPluginPath"
  >,
): string {
  const source = (path: string) => stringifyEsmImportSpecifier(resolvePackageSourceFilePath(path));
  return [
    "// Generated by eve. Do not edit by hand.",
    `import ${stringifyEsmImportSpecifier(compiledArtifacts.bootstrapPath)};`,
    `import ${stringifyEsmImportSpecifier(compiledArtifacts.workflowWorldPluginPath)};`,
    ...(runtime.localTracing
      ? [
          `import { installLocalTracing } from ${source("src/internal/nitro/host/local-tracing-runtime.ts")};`,
        ]
      : []),
    ...(runtime.workflowSandbox
      ? [
          `import { installWorkflowSandboxRuntime } from ${source("src/internal/nitro/host/workflow-sandbox-runtime.ts")};`,
        ]
      : []),
    "",
    "export default function eveRuntimePlugin(nitroApp) {",
    ...(runtime.localTracing ? ["  installLocalTracing(nitroApp);"] : []),
    ...(runtime.workflowSandbox ? ["  installWorkflowSandboxRuntime();"] : []),
    "}",
    "",
  ].join("\n");
}
