import { createHash } from "node:crypto";
import { mkdir, rm, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

import {
  comparePaths,
  createDiskSkillFileSource,
  MAX_SKILL_FILE_BYTES,
  type SkillFilesIndex,
  type SkillFilesIndexEntry,
} from "#channel/skill-files.js";
import {
  stringifyEsmImportSpecifier,
  stringifyNitroDataImportSpecifier,
} from "#internal/application/import-specifier.js";
import { resolvePackageSourceFilePath } from "#internal/application/package.js";

/** The Nitro virtual id of the generated plugin that installs a build's skill files. */
export const SKILL_FILES_PLUGIN_ID = "#eve/skill-files";

/**
 * Stages the root agent's materialized `skills/` tree for a production build
 * and returns the source of the `#eve/skill-files` Nitro plugin that embeds it.
 *
 * The listing and bytes come from {@link createDiskSkillFileSource}, the same
 * source dev reads, so both modes agree on which files exist. Each shipped
 * file is staged once per SHA-256 and loaded lazily through a `bytes:`
 * import, so authored names never reach an import specifier and Nitro's
 * `replace` never sees the contents. The index loads through `text:`. Files
 * over {@link MAX_SKILL_FILE_BYTES} are indexed by size only, and directories
 * are indexed so empty ones survive the build.
 */
export async function writeSkillFilesPlugin(input: {
  readonly skills: readonly string[];
  /** The materialized `skills/` directory of the root agent's workspace resources. */
  readonly skillsRoot: string;
  /** Build-owned directory the staged files and the index are written to. */
  readonly stagingDirectory: string;
}): Promise<string> {
  const source = createDiskSkillFileSource(resolve(input.skillsRoot));
  const filesDirectory = join(input.stagingDirectory, "files");
  await rm(input.stagingDirectory, { force: true, recursive: true });
  await mkdir(filesDirectory, { recursive: true });

  const shipped = new Set<string>();
  const skills: [string, SkillFilesIndexEntry[], readonly string[]][] = [];
  for (const skill of [...new Set(input.skills)].sort(comparePaths)) {
    const files: SkillFilesIndexEntry[] = [];
    for (const { path, size } of await source.listFiles(skill)) {
      if (size > MAX_SKILL_FILE_BYTES) {
        files.push([path, size, null]);
        continue;
      }
      // Hash and stage the bytes that were read, not a second read of the path.
      const bytes = await source.readFile(skill, path);
      const sha256 = createHash("sha256").update(bytes).digest("hex");
      if (!shipped.has(sha256)) {
        await writeFile(join(filesDirectory, sha256), bytes);
        shipped.add(sha256);
      }
      files.push([path, bytes.byteLength, sha256]);
    }
    skills.push([skill, files, await source.listDirectories(skill)]);
  }

  const indexPath = join(input.stagingDirectory, "index.json");
  await writeFile(indexPath, JSON.stringify({ skills } satisfies SkillFilesIndex));
  return [
    "// Generated by eve. Do not edit by hand.",
    `import index from ${stringifyNitroDataImportSpecifier("text", indexPath)};`,
    `import { installBundledSkillFiles } from ${stringifyEsmImportSpecifier(resolvePackageSourceFilePath("src/channel/skill-files.ts"))};`,
    "const files = {",
    ...[...shipped].map(
      (sha256) =>
        `  ${JSON.stringify(sha256)}: () => import(${stringifyNitroDataImportSpecifier("bytes", join(filesDirectory, sha256))}),`,
    ),
    "};",
    "export default function installSkillFilesPlugin() {",
    "  installBundledSkillFiles({ index, read: async (sha256) => (await files[sha256]()).default });",
    "}",
    "",
  ].join("\n");
}
