import { readFile, writeFile } from "node:fs/promises";
const assets = {};
for (const [path, file, type] of [
  ["/", "index.html", "text/html"],
  ["/assets/web.js", "dist/app.js", "application/javascript"],
  ["/assets/web.css", "style.css", "text/css"],
  ...["geist.woff2", "geist-mono.woff2", "eve-logo.svg", "eve-icon.svg", "favicon.svg"].map(
    (file) => [
      "/assets/" + file,
      "assets/" + file,
      file.endsWith("woff2") ? "font/woff2" : "image/svg+xml",
    ],
  ),
]) {
  let bytes = await readFile(new URL("./web/" + file, import.meta.url));
  if (!file.endsWith("woff2"))
    bytes = Buffer.from(
      bytes
        .toString()
        .replaceAll("/assets/", "/start/assets/")
        .replaceAll("/v1/web/", "/start/v1/web/")
        .replaceAll('href="/"', 'href="/start"'),
    );
  assets[path] = { body: bytes.toString("base64"), type };
}
await writeFile(
  new URL("src/assets.ts", import.meta.url),
  "// Generated by build-assets.mjs.\nexport const assets=" + JSON.stringify(assets) + ";\n",
);

// Bundle the canonical relay SDK into this distribution, without unpublished workspace dependencies.
for (const [name, source] of [
  ["relay-client", "sdk"],
  ["relay-protocol", "protocol"],
]) {
  let code = await readFile(new URL("../" + source + "/src/index.ts", import.meta.url), "utf8");
  code = code.replace(/(["'])@eve-start\/protocol\1/g, "$1./relay-protocol.ts$1");
  await writeFile(
    new URL("src/" + name + ".ts", import.meta.url),
    "// Generated from packages/" + source + "/src/index.ts.\n" + code,
  );
}

const copies = [
  ["computer-routes", "./server/browser/routes.ts"],
  ["computer-app", "./server/browser/app.ts"],
  ["computer-db", "./server/db.ts"],
  ["computer-desktop", "./desktop/src/manager.ts"],
  ["connector-app", "./server/app.ts"],
  ["relay-pairing", "./server/pairing.ts"],
  ["conversation", "./server/conversation.ts"],
  ["content-retention", "./server/retention.ts"],
];
for (const [name, path] of copies) {
  let code = await readFile(new URL(path, import.meta.url), "utf8");
  for (const [before, after] of Object.entries({
    "../../protocol/src/conversation.ts": "./conversation-events.ts",
    "@eve-start/protocol": "./relay-protocol.ts",
    "../retention.ts": "./content-retention.ts",
    "../db.ts": "./computer-db.ts",
    "../../server/db.ts": "./computer-db.ts",
    "./routes.ts": "./computer-routes.ts",
    "../app.ts": "./connector-app.ts",
    "./db.ts": "./computer-db.ts",
    "./pairing.ts": "./relay-pairing.ts",
    "./conversation.ts": "./conversation.ts",
    "./retention.ts": "./content-retention.ts",
    "./browser/routes.ts": "./computer-routes.ts",
    "@eve-start/sdk": "./relay-client.ts",
    "../src/sandbox-database.ts": "./sandbox-database.ts",
  }))
    code = code.replaceAll(before, after);
  await writeFile(
    new URL("src/" + name + ".ts", import.meta.url),
    "// Generated from " + path + ".\n" + code,
  );
}
const computerAssets = {};
for (const name of [
  "package.json",
  "install.sh",
  "start.sh",
  "runner.mjs",
  "chrome.mjs",
  "access.mjs",
  "daemon.mjs",
  "ctl.mjs",
  "index.html",
  "eve-logo.svg",
  "favicon.svg",
  "geist.woff2",
  "geist-mono.woff2",
])
  computerAssets[name] = (
    await readFile(new URL("./desktop/runtime/" + name, import.meta.url))
  ).toString("base64");
computerAssets["protocol.mjs"] = (
  await readFile(new URL("../protocol/dist/index.js", import.meta.url))
).toString("base64");
await writeFile(
  new URL("src/computer-assets.ts", import.meta.url),
  "// Generated runtime assets.\nexport default " + JSON.stringify(computerAssets) + ";\n",
);

await writeFile(
  new URL("src/conversation-events.ts", import.meta.url),
  await readFile(new URL("../protocol/src/conversation.ts", import.meta.url)),
);

// The Expo export is optional: without it, the dashboard offers only native/Metro pairing.
let mobileBundle = "null";
try {
  mobileBundle = JSON.stringify(
    await readFile(new URL("../../.eve/mobile-export/bundle.json", import.meta.url), "utf8"),
  );
  mobileBundle = "JSON.parse(" + mobileBundle + ")";
} catch (error) {
  if (error.code !== "ENOENT") throw error;
}
await writeFile(
  new URL("src/mobile-assets.ts", import.meta.url),
  "// Generated by build-assets.mjs from scripts/build-mobile-bundle.mjs.\nimport type { MobileBundle } from './mobile.ts';\nconst bundle: MobileBundle | null = " +
    mobileBundle +
    ";\nexport default bundle;\n",
);

const databaseAssets = {};
for (const name of ["server.mjs", "setup.sh"])
  databaseAssets[name] = (await readFile(new URL("./database/" + name, import.meta.url))).toString(
    "base64",
  );
await writeFile(
  new URL("src/database-assets.ts", import.meta.url),
  "// Generated database runtime assets.\nexport default " + JSON.stringify(databaseAssets) + ";\n",
);
