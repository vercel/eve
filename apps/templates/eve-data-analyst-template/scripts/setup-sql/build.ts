/**
 * Builds the SQL that creates the agent's read-only Postgres roles.
 *
 * @packageDocumentation
 */
import { isSafeIdentifier, isSafeSchemaName } from "#lib/analyst/identifiers";

/** Characters allowed in a generated or supplied login password, so it needs no SQL escaping. */
const PASSWORD = /^[A-Za-z0-9_.~-]{16,128}$/u;

/** Inputs for the role setup script. */
export interface SetupSqlOptions {
  /** Base read-only role every caller inherits from. */
  readonly baseRole: string;
  /** Login role the agent connects as. */
  readonly login: string;
  /** Password for a newly created login role. */
  readonly password: string;
  /** Schemas the agent explores, from `ANALYST_SCHEMAS`. */
  readonly schemas: readonly string[];
  /** Reset the password if the login role already exists. */
  readonly setPassword: boolean;
  /**
   * Schemas whose tables the base role can read, from `ANALYST_SHARED_SCHEMAS`.
   * @remarks Must be a subset of `schemas`. The rest of `schemas` are restricted: the SQL grants nothing in them.
   */
  readonly sharedSchemas: readonly string[];
  /** Additional team roles from ANALYST_ROLE_MAP. */
  readonly teamRoles: readonly string[];
}

const assertIdentifier = (
  label: string,
  value: string,
  isSafe: (name: string) => boolean = isSafeIdentifier
) => {
  if (!isSafe(value)) {
    throw new Error(
      `${label} "${value}" isn't a safe Postgres identifier. Use lowercase letters, digits, and underscores.`
    );
  }
};

const createRole = (role: string, options: string) => `DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${role}') THEN
    CREATE ROLE ${role} ${options};
  END IF;
END
$$;`;

/**
 * Builds idempotent SQL that creates the read-only roles and the agent's login.
 *
 * @param options - Role names, explored and shared schemas, and login password.
 * @returns SQL to run as a database owner, for example by piping it into psql.
 * @throws {@link Error} When any identifier or the password is unsafe to interpolate, or a shared schema isn't in `schemas`.
 * @remarks The login role is NOINHERIT and holds no data grants, so it can read nothing until the agent runs `SET LOCAL ROLE` into an analyst role. The base role gets `USAGE` and `SELECT` on every existing table in `sharedSchemas` each time the SQL runs, so a table-level `REVOKE` from the base role there doesn't survive the next run. Restricted schemas get no grants at all, not even `USAGE`, because team roles inherit the base role. The SQL never revokes anything, so a schema moved from shared to restricted keeps its earlier grants until an admin revokes them.
 */
export const buildSetupSql = ({
  baseRole,
  login,
  password,
  schemas,
  setPassword,
  sharedSchemas,
  teamRoles,
}: SetupSqlOptions): string => {
  assertIdentifier("Default role", baseRole);
  assertIdentifier("Login role", login);
  for (const schema of [...schemas, ...sharedSchemas]) {
    assertIdentifier("Schema", schema, isSafeSchemaName);
  }
  const unlisted = sharedSchemas.filter((schema) => !schemas.includes(schema));
  if (unlisted.length > 0) {
    throw new Error(
      `Shared schema ${unlisted.join(", ")} must also be listed in ANALYST_SCHEMAS.`
    );
  }
  const teams = [...new Set(teamRoles)].filter((role) => role !== baseRole);
  for (const role of teams) {
    assertIdentifier("ANALYST_ROLE_MAP role", role);
  }
  if (login === baseRole || teams.includes(login)) {
    throw new Error("The login role must differ from every analyst role.");
  }
  if (!PASSWORD.test(password)) {
    throw new Error(
      "The login password must be 16 to 128 characters of letters, digits, '_', '.', '~', or '-'."
    );
  }
  if (sharedSchemas.length === 0) {
    throw new Error("List at least one shared schema.");
  }
  const sharedList = [...new Set(sharedSchemas)].join(", ");
  const restricted = [...new Set(schemas)].filter(
    (schema) => !sharedSchemas.includes(schema)
  );
  const teamExample = restricted.length > 0 ? restricted.join(", ") : "billing";
  const parts = [
    `-- Generated by scripts/setup-sql.ts. Run as a database owner; it's safe to run again.
BEGIN;

-- Base read-only role. Every caller queries as this role or one that inherits it.
${createRole(baseRole, "NOLOGIN")}
-- Shared schemas (ANALYST_SHARED_SCHEMAS).
GRANT USAGE ON SCHEMA ${sharedList} TO ${baseRole};
-- Every table, view, and foreign table in these schemas. Running this again re-grants each one, which undoes a
-- REVOKE on a single table. Row-level security policies are unaffected.
GRANT SELECT ON ALL TABLES IN SCHEMA ${sharedList} TO ${baseRole};
-- Tables created later by the role running this script. Repeat with FOR ROLE <owner> for other owners.
ALTER DEFAULT PRIVILEGES IN SCHEMA ${sharedList} GRANT SELECT ON TABLES TO ${baseRole};`,
  ];
  if (restricted.length > 0) {
    parts.push(`
-- Restricted schemas (in ANALYST_SCHEMAS but not ANALYST_SHARED_SCHEMAS): ${restricted.join(", ")}.
-- Nothing here is granted to ${baseRole}. Grant USAGE and SELECT to the team roles that need them.
-- If a schema was shared before, revoke what earlier runs granted:
-- REVOKE SELECT ON ALL TABLES IN SCHEMA ${restricted.join(", ")} FROM ${baseRole};
-- REVOKE USAGE ON SCHEMA ${restricted.join(", ")} FROM ${baseRole};
-- ALTER DEFAULT PRIVILEGES IN SCHEMA ${restricted.join(", ")} REVOKE SELECT ON TABLES FROM ${baseRole};`);
  }
  for (const role of teams) {
    parts.push(`
-- Team role from ANALYST_ROLE_MAP. It inherits the base grants.
${createRole(role, `NOLOGIN IN ROLE ${baseRole}`)}
-- TODO: grant this team its extra access, for example:
-- GRANT USAGE ON SCHEMA ${teamExample} TO ${role};
-- GRANT SELECT ON ALL TABLES IN SCHEMA ${teamExample} TO ${role};
-- Or restrict rows with row-level security policies on current_user.`);
  }
  parts.push(`
-- Login role the agent connects as. NOINHERIT with no data grants: it can only SET ROLE into the analyst roles.
${createRole(login, `LOGIN NOINHERIT PASSWORD '${password}'`)}${
    setPassword ? `\nALTER ROLE ${login} PASSWORD '${password}';` : ""
  }
GRANT ${[baseRole, ...teams].join(", ")} TO ${login};
ALTER ROLE ${login} SET default_transaction_read_only = on;
ALTER ROLE ${login} SET statement_timeout = '60s';
ALTER ROLE ${login} SET idle_in_transaction_session_timeout = '60s';

COMMIT;

-- Optional hardening when ANALYST_ROLE_MAP lists more than one role (self-hosted Postgres only; affects every
-- role in the database, and managed providers may not allow it). It stops a query from switching roles with
-- set_config(); the agent itself only uses SET LOCAL statements, which are unaffected:
-- REVOKE EXECUTE ON FUNCTION pg_catalog.set_config(text, text, boolean) FROM PUBLIC;`);
  return parts.join("\n");
};
